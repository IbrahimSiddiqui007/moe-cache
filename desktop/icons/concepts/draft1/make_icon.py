#!/usr/bin/env python3
"""Build the moe-cache icon from its text pixel maps (icon32.txt = the 32x32 master, icon16.txt = the hand-placed 16x16 for small sizes).
Edit the .txt maps, then run:  python3 desktop/icons/make_icon.py   (needs Pillow; writes icon.svg, icon-small.svg, preview.png and out/*.png)
Palette (control page): S sky #6b99b3, C cream #f8efc9, K dark brown #2a1b14, R red-orange #c8442a, M mid #c6ceb8; '.' = transparent (the stepped corners).
Flat colours, hard edges, no anti-aliasing: every size is a nearest-neighbour scale of a map."""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
PAL = {"S": (0x6B, 0x99, 0xB3, 255), "C": (0xF8, 0xEF, 0xC9, 255), "K": (0x2A, 0x1B, 0x14, 255), "R": (0xC8, 0x44, 0x2A, 255),
       "M": (0xC6, 0xCE, 0xB8, 255), ".": (0, 0, 0, 0)}
HEX = {k: "#%02x%02x%02x" % v[:3] for k, v in PAL.items() if k != "."}


def load(name):
    rows = [r for r in open(os.path.join(HERE, name)).read().split() if r]
    n = len(rows)
    assert all(len(r) == n for r in rows) and all(c in PAL for r in rows for c in r), name
    return rows


def image(rows, scale=1):
    n = len(rows)
    im = Image.new("RGBA", (n, n))
    im.putdata([PAL[c] for r in rows for c in r])
    return im.resize((n * scale, n * scale), Image.NEAREST) if scale != 1 else im


def svg(rows, name):
    n, u = len(rows), 1024 // len(rows)
    rects = "\n".join(f'  <rect x="{x*u}" y="{y*u}" width="{u}" height="{u}" fill="{HEX[c]}"/>'
                      for y, r in enumerate(rows) for x, c in enumerate(r) if c != ".")
    open(os.path.join(HERE, name), "w").write(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024" shape-rendering="crispEdges">\n'
        f'  <!-- generated by make_icon.py from the text pixel map; one rect per pixel -->\n{rects}\n</svg>\n')


big, small = load("icon32.txt"), load("icon16.txt")
svg(big, "icon.svg"); svg(small, "icon-small.svg")
out = os.path.join(HERE, "out"); os.makedirs(out, exist_ok=True)
for px, src, name in [(16, small, "16"), (32, big, "32"), (48, small, "48"), (64, big, "64"), (128, big, "128"), (256, big, "256"), (512, big, "512"), (1024, big, "1024")]:
    image(src, px // len(src)).save(os.path.join(out, name + ".png"))

# preview: 16, 32, 64, 256, 1024 (shown at 512) at their real pixel size, on light and dark; below, 16 and 32 enlarged x8 / x4
tiles = [image(small), image(big), image(big, 2), image(big, 8), image(big, 16)]
tiles[-1] = tiles[-1].resize((512, 512), Image.NEAREST)
W = 40 + sum(t.width + 40 for t in tiles); H = 512 + 80
sheet = Image.new("RGB", (W, H * 2 + 220))
for row, bg in enumerate([(246, 248, 250), (22, 27, 34)]):
    sheet.paste(Image.new("RGB", (W, H), bg), (0, row * H)); x = 40
    for t in tiles:
        sheet.paste(t, (x, row * H + 40 + (512 - t.height) // 2), t); x += t.width + 40
sheet.paste(Image.new("RGB", (W, 220), (246, 248, 250)), (0, H * 2)); x = 40
for t, z in [(image(small), 8), (image(big), 4)]:
    t = t.resize((t.width * z, t.height * z), Image.NEAREST); sheet.paste(t, (x, H * 2 + 40), t); x += t.width + 40
sheet.save(os.path.join(HERE, "preview.png"))
print("wrote icon.svg, icon-small.svg, preview.png, out/*.png")
