#!/usr/bin/env python3
"""SERVER-005: `moe-cache-server MODEL --print-systemd` fills docs/moe-cache-server.service with the user's paths and memory limits. No model, nothing started.
   python3 tests/print_systemd_test.py"""
import os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(HERE, "bin"))
import moe_cache as mc  # noqa: E402

fails = []
def check(ok, what):
    print(("  ok   " if ok else "  FAIL ") + what)
    if not ok:
        fails.append(what)

TMP = tempfile.mkdtemp(prefix="moe-systemd-")
ls = os.path.join(TMP, "my llama", "llama-server"); os.makedirs(os.path.dirname(ls)); open(ls, "w").close()
model = os.path.join(TMP, "Model 100%$.gguf"); open(model, "w").close()

def unit(*args):
    a, extra, argv = mc.parse_server([model, "--llama-server", ls, *args])
    return mc.systemd_unit(a, extra, argv)

text, notes = unit("--agent", "--ram", "20", "--print-systemd")
ex = [l for l in text.splitlines() if l.startswith("ExecStart=")]
check(len(ex) == 1 and os.path.join(HERE, "bin", "moe-cache-server") in ex[0], "ExecStart names this kit's launcher by absolute path")
check('"' + model.replace("%", "%%").replace("$", "$$") + '"' in ex[0], "the model path is quoted, % and $ doubled (systemd expands both)")
check('"' + ls + '"' in ex[0] and "--agent" in ex[0] and "--ram 20" in ex[0] and "--print-systemd" not in ex[0], "llama-server (path with a space), --agent and --ram kept; --print-systemd dropped")
check("MemoryMax=19G" in text and "MemoryHigh=17G" in text, "--ram 20 GB (18.6 GiB): MemoryMax 19G, MemoryHigh 17G (92 %, rounded down)")
check(text.count("MemoryMax=") == 1 and text.count("MemoryHigh=") == 1 and "[Install]" in text and "WantedBy=default.target" in text, "the rest of the template is kept, each limit once")
check("EDIT 1:" not in text and "Generated by moe-cache-server --print-systemd" in text, "the edit-me comment for ExecStart says the line is generated")

text, notes = unit("--api-key", "SECRET-KEY-123", "--print-systemd")
check("SECRET-KEY-123" not in text and any("--api-key left out" in n for n in notes), "--api-key VALUE never reaches the unit; a note says what to do")
text, notes = unit("--api-key=SECRET-KEY-123", "--print-systemd")
check("SECRET-KEY-123" not in text and any("--api-key left out" in n for n in notes), "--api-key=VALUE too")

text, _ = unit("--print-systemd", "--", "--metrics", "-c", "8192")
check("--" in [w for w in re.split(r"\s+", [l for l in text.splitlines() if l.startswith("ExecStart=")][0])] and "--metrics" in text, "options after -- stay after --")

# the word quoting
check(mc.unit_word("plain") == "plain" and mc.unit_word("a b") == '"a b"' and mc.unit_word('a"b') == '"a\\"b"' and mc.unit_word("100%") == "100%%" and mc.unit_word("$HOME") == "$$HOME", "unit_word: quotes spaces and quotes, doubles % and $")

# the command: stdout is the unit only, notes go to stderr
r = subprocess.run([sys.executable, os.path.join(HERE, "bin", "moe_cache.py"), "server", model, "--llama-server", ls, "--ram", "20", "--print-systemd"], capture_output=True, text=True)
check(r.returncode == 0 and r.stdout.startswith("# Always-on") and "MemoryMax=19G" in r.stdout and "moe-cache: MemoryMax=19G" in r.stderr and "ExecStart=" not in r.stderr, "the command prints only the unit on stdout (redirect it into the unit file), the note on stderr")
r = subprocess.run([sys.executable, os.path.join(HERE, "bin", "moe_cache.py"), "server", "--print-systemd"], capture_output=True, text=True)
check(r.returncode != 0 and "needs the model" in (r.stderr + r.stdout), "no model: a clear refusal")
sys.exit(1 if fails else 0)
