#!/usr/bin/env python3
"""The to-do list for claim markers (DOCS-621): every line of README.md and docs/benchmark_card.html that shows a performance number and has no
current `<!-- claim:ID -->`, with the numbers the lint saw, the line's text, and the claims whose title or text contains one of those numbers
(candidates, to be checked by a person; a match on a number alone is not proof). Read-only; it changes no file.
   python3 tools/claim_worklist.py [FILE ...] > worklist.md        (default: README.md and docs/benchmark_card.html)
Uses bin/moe_cache_claims.py (the same rules as `bench-record lint`)."""
import html, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "bin"))
import moe_cache_claims as mc


def plain(line):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", line))).strip()


def norm(n):
    return n.replace("×", "x").replace("−", "-").replace(" ", "").lower()


def main(argv):
    files = argv or [os.path.join(ROOT, "README.md"), os.path.join(ROOT, "docs", "benchmark_card.html")]
    claims, runs = mc.load_claims(mc.BENCH), mc.load_runs(mc.BENCH)
    status, _ = mc.compute_status(claims, runs)
    blob = {i: norm(str(c)) for i, c in claims.items()}
    print("# Claim-marker worklist (generated by tools/claim_worklist.py)\n")
    total = 0
    for f in files:
        probs, shown, ok = mc.lint_file(f, claims, status)
        rel = os.path.relpath(f, ROOT)
        lines = open(f, encoding="utf-8").read().splitlines()
        print(f"## {rel}: {shown} lines show numbers, {ok} with a current claim, {len(probs)} to do\n")
        print("| Line | Kind | Numbers / claim | Text | Candidate claims (number found in the claim) |\n|---|---|---|---|---|")
        for n, kind, text in probs:
            nums = [norm(x) for x in text.split(", ")] if kind == "unclaimed" else []
            cand = sorted(i for i in claims if any(x and x in blob[i] for x in nums))[:5]
            print(f"| {n} | {kind} | {text} | {plain(lines[n - 1])[:140].replace('|', '/')} | {', '.join(f'`{c}` ({status[c][0]})' for c in cand) or '-'} |")
            total += 1
        print()
    print(f"{total} lines in all.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
